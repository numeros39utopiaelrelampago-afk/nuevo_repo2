git init - crea un nuevo repo
git add . - agrega al repo local
git commit -m "mensaje" - crea nueva version del repo local
git push origin rama - sube los cambios de local a remoto
git pull origin rama - baja los cambios de local a remoto
git clone repo - clona por 1° vez de remoto a local
git checkout -b rama - crea una nueva rama y se mueve a ella
git checkout rama - moverse de rama (o de version dentro de una linea de codigo)
git merge rama - absorbe otra rama a la rama actual
git status - muestra los cambios locales
git log - muestra la historia local
git branch - muestra todas las ramas
git branch -D rama - elimina una rama

